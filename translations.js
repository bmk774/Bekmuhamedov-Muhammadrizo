// Language Swither Logic
document.addEventListener('DOMContentLoaded', () => {
    const langBtns = document.querySelectorAll('.lang-btn');
    const elementsToTranslate = document.querySelectorAll('[data-i18n]');
    const placeholdersToTranslate = document.querySelectorAll('[data-i18n-placeholder]');
    
    // Check localStorage for saved lang
    let currentLang = localStorage.getItem('portfolio-lang') || 'ru';
    setLanguage(currentLang);

    langBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            const lang = btn.getAttribute('data-lang');
            setLanguage(lang);
        });
    });

    function setLanguage(lang) {
        if (!translations[lang]) return;
        
        localStorage.setItem('portfolio-lang', lang);
        document.documentElement.lang = lang;

        // Update buttons
        langBtns.forEach(btn => {
            if (btn.getAttribute('data-lang') === lang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });

        // Translate text content
        elementsToTranslate.forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                el.innerHTML = translations[lang][key]; // Using innerHTML if needed, but textContent is safer
            }
        });

        // Translate placeholders
        placeholdersToTranslate.forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (translations[lang][key]) {
                el.setAttribute('placeholder', translations[lang][key]);
            }
        });
    }
});
